function h = add_n_textbox(obj, ax, txt)
%ADD_N_TEXTBOX writes txt (sample size, overflow counts) in the top-left corner
% of ax in the toolbox text style.
    h = text(ax, 0.01, 1, txt, ...
        Units="normalized", ...
        FontSize=obj.FONT_SIZE_TEXT, ...
        FontName=obj.FONT_NAME_TEXT, ...
        FontWeight=obj.FONT_WEIGHT_TEXT, ...
        HorizontalAlignment="left", ...
        VerticalAlignment="top", ...
        BackgroundColor="white");
end
